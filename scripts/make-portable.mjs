import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, "..");
const distDir = path.join(projectRoot, "dist");
const inputPath = path.join(distDir, "index.html");
const outputPath = path.join(distDir, "MatrixBlockCanvas-portable.html");

const isLocalAsset = (ref) => {
  if (!ref) return false;
  if (/^(?:[a-z]+:|\/\/|#)/i.test(ref)) return false;
  return true;
};

const resolveAsset = (ref) => {
  const cleanRef = ref.split(/[?#]/, 1)[0].replace(/^\.\//, "");
  const resolved = path.resolve(distDir, cleanRef);
  const relative = path.relative(distDir, resolved);
  if (relative.startsWith("..") || path.isAbsolute(relative)) {
    throw new Error(`Asset escaped dist/: ${ref}`);
  }
  return resolved;
};

const escapeInlineScript = (source) => source.replace(/<\/script/gi, "<\\/script");
const escapeInlineStyle = (source) => source.replace(/<\/style/gi, "<\\/style");
const stripRemoteCssImports = (source) =>
  source.replace(/@import\s+(?:url\()?(['"])(https?:\/\/[^'"]+)\1\)?\s*;\s*/gi, "");

let html = await readFile(inputPath, "utf8");
let inlinedScripts = 0;
let inlinedStyles = 0;
let removedRemoteCssImports = 0;

const scriptTags = [...html.matchAll(/<script\b[^>]*\bsrc=(['"])([^'"]+)\1[^>]*><\/script>/gi)];
const localScriptTags = scriptTags.filter((match) => isLocalAsset(match[2]));

for (const match of localScriptTags) {
  const [tag, , ref] = match;
  const source = await readFile(resolveAsset(ref), "utf8");
  const openingTag = tag.match(/^<script\b([^>]*)>/i)?.[1] ?? "";
  const attrs = openingTag
    .replace(/\s+src=(['"])[^'"]+\1/i, "")
    .replace(/\s+crossorigin(?:=(['"])[^'"]*\1)?/i, "")
    .replace(/\s+type=(['"])module\1/i, "");
  const replacement = `<script${attrs}>\n${escapeInlineScript(source)}\n</script>`;
  html = html.replace(tag, replacement);
  inlinedScripts += 1;
}

const linkTags = [...html.matchAll(/<link\b[^>]*>/gi)];
const localStylesheetTags = linkTags.filter((match) => {
  const tag = match[0];
  const rel = tag.match(/\brel=(['"])([^'"]+)\1/i)?.[2]?.toLowerCase();
  const ref = tag.match(/\bhref=(['"])([^'"]+)\1/i)?.[2];
  return rel === "stylesheet" && Boolean(ref && isLocalAsset(ref));
});

for (const match of localStylesheetTags) {
  const tag = match[0];
  const ref = tag.match(/\bhref=(['"])([^'"]+)\1/i)?.[2];
  if (!ref) continue;

  const originalSource = await readFile(resolveAsset(ref), "utf8");
  const remoteImports = originalSource.match(/@import\s+(?:url\()?(['"])(https?:\/\/[^'"]+)\1\)?\s*;/gi) ?? [];
  removedRemoteCssImports += remoteImports.length;
  const source = stripRemoteCssImports(originalSource);

  html = html.replace(tag, `<style>\n${escapeInlineStyle(source)}\n</style>`);
  inlinedStyles += 1;
}

if (localScriptTags.length === 0 || inlinedScripts !== localScriptTags.length) {
  throw new Error(
    `Portable build failed while inlining JavaScript (${inlinedScripts}/${localScriptTags.length}).`,
  );
}

if (inlinedStyles !== localStylesheetTags.length) {
  throw new Error(
    `Portable build failed while inlining stylesheets (${inlinedStyles}/${localStylesheetTags.length}).`,
  );
}

const remainingRemoteCssImports = html.match(/@import\s+(?:url\()?['"]https?:\/\//gi) ?? [];
if (remainingRemoteCssImports.length > 0) {
  throw new Error("Portable build still contains remote CSS imports.");
}

const banner = `<!-- Matrix Block Canvas portable build. Generated by scripts/make-portable.mjs. -->\n`;
await writeFile(outputPath, banner + html, "utf8");

console.log(`Portable HTML created: ${path.relative(projectRoot, outputPath)}`);
console.log(`Inlined ${inlinedScripts} script bundle(s) and ${inlinedStyles} stylesheet(s).`);
console.log(`Removed ${removedRemoteCssImports} remote CSS import(s) for offline use.`);
